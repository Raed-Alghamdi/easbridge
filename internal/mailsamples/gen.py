#!/usr/bin/env python3
"""Writes samples.go: Arabic texts in windows-1256, ISO-8859-6 and UTF-8 with their RFC 2047 B and Q forms and
their bodies in 8bit, base64 and quoted-printable. Python's codecs are an implementation independent of
golang.org/x/text, so the Go tests do not check the decoder against itself. Run it with `go generate`."""
import base64
import quopri

SUBJECT = "تقرير الربع الأول"  # First quarter report
NAME = "محمد العتيبي"  # Mohammed Al-Otaibi
BODY = "مرحبا بالعالم\r\nهذا اختبار للبريد العربي\r\n"  # Hello world / this is a test of Arabic mail
LONG = "اجتماع فريق المبيعات الأسبوعي لمناقشة خطة الربع القادم وتقارير الأداء والميزانية المقترحة"
CHARSETS = ["windows-1256", "iso-8859-6", "utf-8"]


def go(b):
    """A Go string literal for the bytes."""
    out = []
    for x in b:
        if x == 0x22:
            out.append('\\"')
        elif x == 0x5C:
            out.append("\\\\")
        elif x == 0x0D:
            out.append("\\r")
        elif x == 0x0A:
            out.append("\\n")
        elif 0x20 <= x < 0x7F:
            out.append(chr(x))
        else:
            out.append("\\x%02x" % x)
    return '"' + "".join(out) + '"'


def q_word(cs, raw):
    s = ""
    for x in raw:
        c = chr(x)
        if x < 128 and c.isalnum():
            s += c
        elif c == " ":
            s += "_"
        else:
            s += "=%02X" % x
    return "=?%s?Q?%s?=" % (cs, s)


def b_word(cs, raw):
    return "=?%s?B?%s?=" % (cs, base64.b64encode(raw).decode())


def wrap76(s):
    return "\r\n".join(s[i : i + 76] for i in range(0, len(s), 76)) + "\r\n"


def qp(raw):
    lines = raw.split(b"\r\n")
    return b"\r\n".join(quopri.encodestring(ln).replace(b"\n", b"\r\n").rstrip(b"\r\n") if ln else b"" for ln in lines)


def split_words(text, cs, kind):
    """The text as encoded-words of at most 75 characters, cut between characters."""
    mk = b_word if kind == "B" else q_word
    pieces, cur = [], ""
    for ch in text:
        trial = cur + ch
        if len(mk(cs, trial.encode(cs))) > 75 and cur:
            pieces.append(cur)
            cur = ch
        else:
            cur = trial
    if cur:
        pieces.append(cur)
    return [mk(cs, p.encode(cs)) for p in pieces]


out = []
w = out.append
w("// Code generated by gen.py (Python's codecs); DO NOT EDIT.")
w("")
w("// Package mailsamples holds Arabic mail in the three charsets and the two RFC 2047 encodings that real")
w("// mailboxes have (windows-1256, ISO-8859-6 and UTF-8; B and Q), for the tests of the MIME code, the IMAP")
w("// front end, the engine and the adapter. The bytes were produced with Python's codecs (gen.py), so a test")
w("// that decodes them does not check the decoder against itself.")
w("package mailsamples")
w("")
w("// Texts, in UTF-8.")
w("const (")
w('\t// Subject is "First quarter report".')
w("\tSubject = %s" % go(SUBJECT.encode()))
w('\t// DisplayName is "Mohammed Al-Otaibi".')
w("\tDisplayName = %s" % go(NAME.encode()))
w('\t// Body is two lines: "Hello world" and "this is a test of Arabic mail".')
w("\tBody = %s" % go(BODY.encode()))
w("\t// LongSubject is long enough to need several encoded-words.")
w("\tLongSubject = %s" % go(LONG.encode()))
w(")")
w("")
w("// Word is a text in one charset and its encoded-word forms.")
w("type Word struct {")
w("\tCharset string // the name an encoded-word and a Content-Type give it")
w("\tText    string // the text, UTF-8")
w("\tRaw     string // the text as bytes in Charset (what a message with 8-bit headers or an 8bit body holds)")
w("\tB       string // =?charset?B?...?=")
w("\tQ       string // =?charset?Q?...?=")
w("}")
w("")
w("// BodyText is a body in one charset with the three transfer encodings.")
w("type BodyText struct {")
w("\tCharset string")
w("\tText    string // UTF-8")
w("\tRaw     string // 8bit: the bytes in Charset")
w("\tBase64  string // base64, 76 characters a line, CRLF")
w("\tQP      string // quoted-printable, CRLF")
w("}")
w("")


def words(var, doc, const, text):
    w("// %s is %s in each charset." % (var, doc))
    w("var %s = []Word{" % var)
    for cs in CHARSETS:
        raw = text.encode(cs)
        w('\t{Charset: "%s", Text: %s, Raw: %s,' % (cs, const, go(raw)))
        w("\t\tB: %s," % go(b_word(cs, raw).encode()))
        w("\t\tQ: %s}," % go(q_word(cs, raw).encode()))
    w("}")
    w("")


words("Subjects", "the subject", "Subject", SUBJECT)
words("Names", "the display name", "DisplayName", NAME)
w("// Bodies is the body in each charset.")
w("var Bodies = []BodyText{")
for cs in CHARSETS:
    raw = BODY.encode(cs)
    w('\t{Charset: "%s", Text: Body, Raw: %s,' % (cs, go(raw)))
    w("\t\tBase64: %s," % go(wrap76(base64.b64encode(raw).decode()).encode()))
    w("\t\tQP: %s}," % go(qp(raw)))
w("}")
w("")
w("// LongSubjects is LongSubject as several encoded-words (none longer than 75 characters, as RFC 2047 says),")
w("// folded onto continuation lines the way mailers write them; either B or Q is set.")
w("var LongSubjects = []Word{")
for cs in CHARSETS:
    for kind in ("B", "Q"):
        joined = "\r\n ".join(split_words(LONG, cs, kind))
        w('\t{Charset: "%s", Text: LongSubject, %s: %s},' % (cs, kind, go(joined.encode())))
w("}")
w("")
raw = SUBJECT.encode("utf-8")
cut = next(i for i in range(5, len(raw)) if (raw[i] & 0xC0) == 0x80)  # inside a character
w("// SplitUTF8 is Subject as two UTF-8 words that cut a character in two (RFC 2047 forbids it, mailers do it).")
w("const SplitUTF8 = %s" % go(("=?utf-8?B?%s?= =?utf-8?B?%s?=" % (base64.b64encode(raw[:cut]).decode(), base64.b64encode(raw[cut:]).decode())).encode()))

open("samples.go", "w", encoding="utf-8").write("\n".join(out) + "\n")

import shutil
import subprocess

if shutil.which("gofmt"):
    subprocess.run(["gofmt", "-w", "samples.go"], check=True)
